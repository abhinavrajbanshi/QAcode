#Python Loops
'''
For loop-
for variable in range():
   statement(s) to be executed

While loop-
variable intialize
while condition:
   statement(s) to be executed

'''
for i in range(1,3):
    print(i)

fruits={"Apple, Mango, Orange"}
for fruit in fruits:
    print(fruit)

usernames={"John", "Ram"}
for users in usernames:
    print("The username are:", users)

i=1
while i<=2:
    print(i)
    i=i+1

count=5
while count>=0:
    print(count)
    count=count-1
print("Happy Birthday!")

